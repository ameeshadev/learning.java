// To  swap two variables without using a third variable 
class Main{
    public static void main(String args[]){
        //declare a variable
        int a=5;
        // declare another variable
        int b=7;
        // then swapping the numbers.
        a=a+b;
        b=a-b;
        System.out.println("a value is:" +a);//12
        System.out.println("b value is:" +b);//5
    }
}
