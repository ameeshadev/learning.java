// variables of java programming language
class Main{
    public static void main (String args[]){
        // there are string,int,char,bool, double etc..
        //Now starts with String variable.
        String name="My name is Ameesha";
        System.out.println("name :" +name);
        //Now start with integer variable
        int num=3;
        System.out.println("Number is:" +num);
        // Now char variable
        char letter='A';
        System.out.println("character is:" +letter);
        //Now Boolean variable.
        boolean value=true;
        System.out.println("boolean is" +value);

    }
}
